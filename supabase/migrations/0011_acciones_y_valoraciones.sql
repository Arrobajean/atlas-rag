-- ── Acciones de escritura que el asistente PROPONE y una persona confirma ───────────────────────────
-- Una sola función para las cuatro acciones: con p_ejecutar = false solo valida y describe lo que haría
-- (vista previa); con true lo hace y deja rastro en `auditoria`. Vista previa y ejecución comparten código.
-- Lista cerrada: nada de SQL libre y ninguna acción puede tocar contratos ni datos personales sensibles.
create or replace function rpc_accion(
  p_tipo text,
  p_datos jsonb,
  p_ejecutar boolean default false,
  p_usuario text default null
) returns jsonb
language plpgsql as $$
declare
  v_id bigint;
  v_txt text;
  v_extra jsonb := '{}'::jsonb;
  -- incidencia
  v_cat text; v_pri text; v_desc text; v_unidad bigint; v_edificio bigint; v_donde text;
  -- cliente / demanda
  v_cliente bigint; v_nombre text; v_tipo_cli text; v_tel text; v_email text; v_dup bigint;
  v_op text; v_max numeric; v_min numeric; v_tipos text[]; v_zonas smallint[]; v_munis integer[]; v_dists integer[];
  v_hab smallint; v_notas text; v_fecha date; v_demanda bigint;
  -- alerta
  v_clave text; v_acc text; v_dias int; v_titulo text;
  -- unidad
  u unidades%rowtype; v_estado text;
begin
  if p_datos is null or jsonb_typeof(p_datos) <> 'object' then
    raise exception 'Faltan los datos de la acción';
  end if;

  if p_tipo = 'crear_incidencia' then
    v_cat := lower(coalesce(nullif(btrim(p_datos ->> 'categoria'), ''), 'otros'));
    if v_cat not in ('fontaneria', 'electricidad', 'calefaccion', 'ascensor', 'cerrajeria', 'humedades', 'electrodomesticos', 'plagas', 'pintura', 'otros') then
      raise exception 'Categoría no válida: %. Usa fontaneria, electricidad, calefaccion, ascensor, cerrajeria, humedades, electrodomesticos, plagas, pintura u otros', v_cat;
    end if;
    v_pri := lower(coalesce(nullif(btrim(p_datos ->> 'prioridad'), ''), 'media'));
    if v_pri not in ('baja', 'media', 'alta', 'urgente') then
      raise exception 'Prioridad no válida: %. Usa baja, media, alta o urgente', v_pri;
    end if;
    v_desc := btrim(coalesce(p_datos ->> 'descripcion', ''));
    if length(v_desc) < 5 or length(v_desc) > 500 then
      raise exception 'La descripción debe tener entre 5 y 500 caracteres';
    end if;
    if nullif(btrim(p_datos ->> 'unidad_ref'), '') is not null then
      select id, edificio_id, referencia into v_unidad, v_edificio, v_donde
        from unidades where upper(referencia) = upper(btrim(p_datos ->> 'unidad_ref'));
      if v_unidad is null then
        raise exception 'No existe la unidad %', btrim(p_datos ->> 'unidad_ref');
      end if;
    elsif nullif(btrim(p_datos ->> 'edificio_ref'), '') is not null then
      select id, referencia into v_edificio, v_donde
        from edificios where upper(referencia) = upper(btrim(p_datos ->> 'edificio_ref'));
      if v_edificio is null then
        raise exception 'No existe el edificio %', btrim(p_datos ->> 'edificio_ref');
      end if;
    else
      raise exception 'Indica la unidad (U-00000) o el edificio (E-00000) de la incidencia';
    end if;

    v_txt := format('Abrir una incidencia de %s (prioridad %s) en %s: «%s»', v_cat, v_pri, v_donde, v_desc);
    if p_ejecutar then
      insert into incidencias (unidad_id, edificio_id, categoria, prioridad, estado, descripcion, fecha_apertura)
      values (v_unidad, case when v_unidad is null then v_edificio end, v_cat, v_pri, 'abierta', v_desc, current_date)
      returning id into v_id;
      insert into auditoria (usuario, tabla, registro_id, columna, valor_nuevo, origen)
      values (p_usuario, 'incidencias', v_id, 'accion_asistente', jsonb_build_object('tipo', p_tipo, 'resumen', v_txt), 'ia');
    end if;
    return jsonb_build_object('ok', true, 'ejecutado', p_ejecutar, 'resumen', v_txt, 'tabla', 'incidencias', 'registro_id', v_id);

  elsif p_tipo = 'crear_cliente_demanda' then
    v_cliente := nullif(btrim(p_datos ->> 'cliente_id'), '')::bigint;
    if v_cliente is not null then
      select nombre into v_nombre from clientes where id = v_cliente;
      if v_nombre is null then
        raise exception 'No existe el cliente %', v_cliente;
      end if;
    else
      v_nombre := btrim(coalesce(p_datos ->> 'nombre', ''));
      if length(v_nombre) < 2 or length(v_nombre) > 120 then
        raise exception 'Indica el nombre del cliente';
      end if;
      v_tipo_cli := lower(coalesce(nullif(btrim(p_datos ->> 'tipo_cliente'), ''), 'inquilino'));
      if v_tipo_cli not in ('inquilino', 'comprador', 'inversor') then
        raise exception 'Tipo de cliente no válido: %. Usa inquilino, comprador o inversor', v_tipo_cli;
      end if;
      v_tel := nullif(btrim(p_datos ->> 'telefono'), '');
      v_email := nullif(lower(btrim(p_datos ->> 'email')), '');
      if v_email is not null and v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
        raise exception 'El email no es válido';
      end if;
      if v_tel is not null then
        select id into v_dup from clientes where regexp_replace(telefono, '\s', '', 'g') = regexp_replace(v_tel, '\s', '', 'g') limit 1;
        if v_dup is not null then
          raise exception 'Ya existe un cliente con ese teléfono (id %). Añade la demanda a ese cliente con cliente_id', v_dup;
        end if;
      end if;
      if v_email is not null then
        select id into v_dup from clientes where lower(email) = v_email limit 1;
        if v_dup is not null then
          raise exception 'Ya existe un cliente con ese email (id %). Añade la demanda a ese cliente con cliente_id', v_dup;
        end if;
      end if;
    end if;

    v_op := lower(coalesce(nullif(btrim(p_datos ->> 'operacion'), ''), ''));
    if v_op not in ('alquiler', 'venta', 'temporada', 'habitaciones') then
      raise exception 'Operación no válida: «%». Usa alquiler, venta, temporada o habitaciones', v_op;
    end if;
    v_max := nullif(btrim(p_datos ->> 'presupuesto_max'), '')::numeric;
    if v_max is null or v_max <= 0 then
      raise exception 'Indica el presupuesto máximo';
    end if;
    v_min := nullif(btrim(p_datos ->> 'presupuesto_min'), '')::numeric;
    if v_min is not null and v_min > v_max then
      raise exception 'El presupuesto mínimo no puede superar al máximo';
    end if;
    v_tipos := case when jsonb_typeof(p_datos -> 'tipos_unidad') = 'array'
                    then array(select lower(x) from jsonb_array_elements_text(p_datos -> 'tipos_unidad') x) else '{}' end;
    if exists (select 1 from unnest(v_tipos) t
               where t not in ('piso', 'atico', 'duplex', 'estudio', 'chalet', 'habitacion', 'local', 'oficina', 'garaje', 'trastero')) then
      raise exception 'Algún tipo de propiedad no es válido';
    end if;
    if jsonb_typeof(p_datos -> 'zonas') = 'array' then
      v_zonas := array(select z.id from jsonb_array_elements_text(p_datos -> 'zonas') n join zonas z on norm(z.nombre) = norm(n));
      if coalesce(cardinality(v_zonas), 0) < jsonb_array_length(p_datos -> 'zonas') then
        raise exception 'Alguna zona no existe. Zonas: Madrid Centro, Madrid Norte, Madrid Oeste, Madrid Sur, Madrid Este, Corredor del Henares, Sur metropolitano, Norte metropolitano, Noroeste y Sierra, Sureste';
      end if;
    end if;
    if jsonb_typeof(p_datos -> 'municipios') = 'array' then
      v_munis := array(select m.id from jsonb_array_elements_text(p_datos -> 'municipios') n join municipios m on norm(m.nombre) = norm(n));
      if coalesce(cardinality(v_munis), 0) < jsonb_array_length(p_datos -> 'municipios') then
        raise exception 'Algún municipio no existe';
      end if;
    end if;
    if jsonb_typeof(p_datos -> 'distritos') = 'array' then
      v_dists := array(select d.id from jsonb_array_elements_text(p_datos -> 'distritos') n join distritos d on norm(d.nombre) = norm(n));
      if coalesce(cardinality(v_dists), 0) < jsonb_array_length(p_datos -> 'distritos') then
        raise exception 'Algún distrito no existe';
      end if;
    end if;
    v_hab := nullif(btrim(p_datos ->> 'habitaciones_min'), '')::smallint;
    v_notas := nullif(btrim(p_datos ->> 'notas'), '');
    if length(coalesce(v_notas, '')) > 500 then
      raise exception 'Las notas no pueden superar 500 caracteres';
    end if;
    v_fecha := nullif(btrim(p_datos ->> 'fecha_entrada'), '')::date;

    v_txt := format('%s con una demanda de %s hasta %s €%s%s',
      case when v_cliente is null then format('Crear el cliente «%s» (%s)', v_nombre, v_tipo_cli) else format('Añadir a «%s»', v_nombre) end,
      v_op, replace(to_char(v_max, 'FM999G999G999G990'), ',', '.'),
      case when coalesce(cardinality(v_zonas), 0) + coalesce(cardinality(v_munis), 0) + coalesce(cardinality(v_dists), 0) > 0
           then ' en ' || array_to_string(array(select jsonb_array_elements_text(coalesce(p_datos -> 'zonas', '[]'::jsonb) || coalesce(p_datos -> 'distritos', '[]'::jsonb) || coalesce(p_datos -> 'municipios', '[]'::jsonb))), ', ') else '' end,
      case when coalesce(cardinality(v_tipos), 0) > 0 then ' · ' || array_to_string(v_tipos, '/') else '' end);

    if p_ejecutar then
      if v_cliente is null then
        insert into clientes (nombre, email, telefono, tipo, notas)
        values (v_nombre, v_email, v_tel, v_tipo_cli, v_notas) returning id into v_cliente;
      end if;
      insert into demandas (cliente_id, operacion, tipos, zona_ids, municipio_ids, distrito_ids, presupuesto_min, presupuesto_max,
                            habitaciones_min, necesita_mascotas, necesita_amueblado, necesita_terraza, fecha_entrada, notas, activa)
      values (v_cliente, v_op::operacion_tipo, v_tipos::tipo_unidad[], coalesce(v_zonas, '{}'), coalesce(v_munis, '{}'), coalesce(v_dists, '{}'),
              v_min, v_max, v_hab, coalesce((p_datos ->> 'necesita_mascotas')::boolean, false),
              coalesce((p_datos ->> 'necesita_amueblado')::boolean, false), coalesce((p_datos ->> 'necesita_terraza')::boolean, false),
              v_fecha, v_notas, true)
      returning id into v_demanda;
      v_id := v_cliente;
      v_extra := jsonb_build_object('cliente_id', v_cliente, 'demanda_id', v_demanda, 'notas', v_notas);
      insert into auditoria (usuario, tabla, registro_id, columna, valor_nuevo, origen)
      values (p_usuario, 'clientes', v_cliente, 'accion_asistente', jsonb_build_object('tipo', p_tipo, 'resumen', v_txt, 'demanda_id', v_demanda), 'ia');
    end if;
    return jsonb_build_object('ok', true, 'ejecutado', p_ejecutar, 'resumen', v_txt, 'tabla', 'clientes', 'registro_id', v_id) || v_extra;

  elsif p_tipo = 'resolver_alerta' then
    v_clave := btrim(coalesce(p_datos ->> 'clave', ''));
    if v_clave = '' then
      raise exception 'Falta la clave de la alerta (sale de alertas_pendientes)';
    end if;
    select titulo into v_titulo from v_alertas where clave = v_clave;
    if v_titulo is null then
      raise exception 'La alerta no existe o ya está resuelta o pospuesta';
    end if;
    v_acc := lower(coalesce(nullif(btrim(p_datos ->> 'accion'), ''), 'resolver'));
    if v_acc not in ('resolver', 'posponer') then
      raise exception 'Acción de alerta no válida: usa resolver o posponer';
    end if;
    v_dias := coalesce(nullif(btrim(p_datos ->> 'dias'), '')::int, 7);
    if v_dias < 1 or v_dias > 90 then
      raise exception 'Los días para posponer deben estar entre 1 y 90';
    end if;
    v_txt := case when v_acc = 'resolver' then format('Marcar como resuelta la alerta «%s»', v_titulo)
                  else format('Posponer %s días la alerta «%s»', v_dias, v_titulo) end;
    if p_ejecutar then
      insert into alertas_estado (clave, estado, hasta, usuario, updated_at)
      values (v_clave, case when v_acc = 'resolver' then 'resuelta' else 'pospuesta' end,
              case when v_acc = 'posponer' then now() + make_interval(days => v_dias) end, p_usuario, now())
      on conflict (clave) do update set estado = excluded.estado, hasta = excluded.hasta, usuario = excluded.usuario, updated_at = now();
      insert into auditoria (usuario, tabla, registro_id, columna, valor_nuevo, origen)
      values (p_usuario, 'alertas_estado', null, 'accion_asistente', jsonb_build_object('tipo', p_tipo, 'resumen', v_txt, 'clave', v_clave), 'ia');
    end if;
    return jsonb_build_object('ok', true, 'ejecutado', p_ejecutar, 'resumen', v_txt, 'tabla', 'alertas_estado', 'registro_id', null);

  elsif p_tipo = 'cambiar_estado_unidad' then
    select * into u from unidades where upper(referencia) = upper(btrim(coalesce(p_datos ->> 'unidad_ref', '')));
    if u.id is null then
      raise exception 'No existe la unidad %', btrim(coalesce(p_datos ->> 'unidad_ref', ''));
    end if;
    v_estado := lower(btrim(coalesce(p_datos ->> 'estado', '')));
    if v_estado not in ('disponible', 'reservada', 'reforma') then
      raise exception 'El asistente solo puede poner una unidad en disponible, reservada o reforma (alquilada y vendida dependen de los contratos)';
    end if;
    if u.estado in ('alquilada', 'vendida') then
      raise exception 'La unidad % está %: ese estado depende de su contrato y no se cambia desde aquí', u.referencia, u.estado;
    end if;
    if exists (select 1 from contratos c where c.unidad_id = u.id and c.tipo <> 'compraventa' and c.estado = 'vigente'
               and current_date between c.fecha_inicio and coalesce(c.fecha_fin, 'infinity'::date)) then
      raise exception 'La unidad % tiene un contrato vigente', u.referencia;
    end if;
    if u.estado::text = v_estado then
      raise exception 'La unidad % ya está en estado %', u.referencia, v_estado;
    end if;
    v_fecha := nullif(btrim(p_datos ->> 'fecha_disponible'), '')::date;
    v_txt := format('Cambiar %s de «%s» a «%s»%s', u.referencia, u.estado, v_estado,
                    case when v_fecha is not null then format(' (disponible desde %s)', to_char(v_fecha, 'DD/MM/YYYY')) else '' end);
    if p_ejecutar then
      update unidades
         set estado = v_estado::estado_unidad,
             fecha_disponible = coalesce(v_fecha, case when v_estado = 'disponible' then current_date else fecha_disponible end)
       where id = u.id;
      insert into auditoria (usuario, tabla, registro_id, columna, valor_anterior, valor_nuevo, origen)
      values (p_usuario, 'unidades', u.id, 'estado', to_jsonb(u.estado::text), to_jsonb(v_estado), 'ia');
    end if;
    return jsonb_build_object('ok', true, 'ejecutado', p_ejecutar, 'resumen', v_txt, 'tabla', 'unidades', 'registro_id', u.id);
  end if;

  raise exception 'Acción no soportada: %', p_tipo;
end $$;

grant execute on function rpc_accion(text, jsonb, boolean, text) to service_role;
