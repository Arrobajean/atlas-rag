-- 0011 · Acciones del asistente (con confirmación humana) y valoraciones de las respuestas

-- Valoración (👍/👎) de cada respuesta del asistente, para que el administrador vea qué falla.
create table if not exists valoraciones_chat (
  id bigint generated by default as identity primary key,
  voto text not null check (voto in ('up', 'down')),
  pregunta text not null,
  respuesta text not null,
  herramientas jsonb not null default '[]'::jsonb,   -- consultas que hizo: [{nombre, descripcion, resumen}]
  fuentes integer not null default 0,
  modelo text,
  comentario text,
  usuario text,
  created_at timestamptz not null default now()
);
create index if not exists valoraciones_chat_idx on valoraciones_chat(voto, created_at desc);
alter table valoraciones_chat enable row level security;

