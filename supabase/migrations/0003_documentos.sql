-- 0003 · Documentos (PDF, MD, TXT) y fragmentos indexados para búsqueda híbrida

do $$ begin
  create type tipo_documento as enum (
    'contrato', 'normas_comunidad', 'acta_junta', 'estatutos', 'inventario',
    'certificado_energetico', 'factura', 'legal', 'procedimiento_interno', 'general');
exception when duplicate_object then null; end $$;

do $$ begin
  create type estado_indexado as enum ('pendiente', 'procesando', 'indexado', 'error');
exception when duplicate_object then null; end $$;

create table if not exists documentos (
  id bigint generated by default as identity primary key,
  titulo text not null,
  tipo tipo_documento not null default 'general',
  edificio_id bigint references edificios(id) on delete set null,
  unidad_id bigint references unidades(id) on delete set null,
  contrato_id bigint references contratos(id) on delete set null,
  storage_path text,                       -- ruta en el bucket privado "documentos"
  mime text,
  hash_sha256 text,
  paginas integer,
  vigente boolean not null default true,
  fecha_documento date,
  sustituye_a bigint references documentos(id) on delete set null,
  estado_indexado estado_indexado not null default 'pendiente',
  error text,
  embedding_model text,
  created_at timestamptz not null default now()
);
create unique index if not exists documentos_hash_uidx on documentos(hash_sha256) where hash_sha256 is not null;
create index if not exists documentos_vinculos_idx on documentos(edificio_id, unidad_id, contrato_id);
create index if not exists documentos_tipo_idx on documentos(tipo, vigente);

do $$ begin
  alter table contratos add constraint contratos_documento_fk
    foreign key (documento_id) references documentos(id) on delete set null;
exception when duplicate_object then null; end $$;

create table if not exists document_chunks (
  id bigint generated by default as identity primary key,
  documento_id bigint not null references documentos(id) on delete cascade,
  orden integer not null,
  pagina integer,
  seccion text,
  contenido text not null,
  embedding vector(768),
  embedding_model text,
  fts tsvector generated always as (to_tsvector('spanish', contenido)) stored,
  unique (documento_id, orden)
);
create index if not exists document_chunks_doc_idx on document_chunks(documento_id);
create index if not exists document_chunks_fts_idx on document_chunks using gin (fts);
create index if not exists document_chunks_embedding_idx
  on document_chunks using hnsw (embedding vector_cosine_ops);

-- Bucket privado para los PDFs (solo existe en Supabase, no en Postgres puro).
do $$ begin
  if to_regclass('storage.buckets') is not null then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('documentos', 'documentos', false, 26214400,
            array['application/pdf', 'text/markdown', 'text/plain'])
    on conflict (id) do nothing;
  end if;
end $$;
