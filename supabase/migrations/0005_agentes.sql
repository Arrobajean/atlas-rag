-- 0005 · Herramientas de agente: demandas de clientes y estado de alertas

create table if not exists demandas (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null references clientes(id) on delete cascade,
  operacion operacion_tipo not null,
  tipos tipo_unidad[] not null default '{}',              -- vacío = cualquiera
  zona_ids smallint[] not null default '{}',              -- vacío = cualquier zona
  municipio_ids integer[] not null default '{}',
  distrito_ids integer[] not null default '{}',
  presupuesto_min numeric(12, 2) check (presupuesto_min >= 0),
  presupuesto_max numeric(12, 2) check (presupuesto_max >= 0),
  habitaciones_min smallint,
  superficie_min numeric(8, 2),
  necesita_mascotas boolean not null default false,
  necesita_amueblado boolean not null default false,
  necesita_terraza boolean not null default false,
  fecha_entrada date,
  notas text,
  activa boolean not null default true,
  created_at timestamptz not null default now(),
  check (presupuesto_max is null or presupuesto_min is null or presupuesto_max >= presupuesto_min)
);
create index if not exists demandas_activa_idx on demandas(activa, operacion);

-- Alertas descartadas o pospuestas por el agente (las alertas en sí se calculan en v_alertas).
create table if not exists alertas_estado (
  clave text primary key,
  estado text not null check (estado in ('resuelta', 'pospuesta')),
  hasta timestamptz,
  usuario text,
  updated_at timestamptz not null default now()
);
