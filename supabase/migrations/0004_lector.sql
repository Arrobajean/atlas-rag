-- 0004 · Lector de documentos con verificación humana
-- Principio: la IA solo escribe en `extracciones` (borrador). Las tablas reales se tocan únicamente
-- al confirmar, y solo con campos definidos en `catalogo_campos` (catálogo cerrado).

create table if not exists catalogo_campos (
  id bigint generated by default as identity primary key,
  clave text not null unique,
  etiqueta text not null,
  ayuda text,
  tipo_documento tipo_documento not null,
  entidad text not null check (entidad in ('contrato', 'inquilino', 'propietario', 'unidad', 'edificio')),
  grupo text not null,
  -- columna: se escribe en tabla_destino.columna_destino · atributo: va a atributos_valores
  -- solo_lectura: se muestra y se compara con la BD, pero nunca se escribe
  escritura text not null check (escritura in ('columna', 'atributo', 'solo_lectura')),
  tabla_destino text check (tabla_destino in ('contratos', 'inquilinos')),
  columna_destino text,
  tipo_dato text not null check (tipo_dato in ('texto', 'numero', 'moneda', 'fecha', 'booleano', 'opcion')),
  obligatorio boolean not null default false,
  opciones jsonb,                          -- array de textos permitidos si tipo_dato = 'opcion'
  validacion jsonb,                        -- {"min":0,"max":31,"regex":"^..$"}
  orden integer not null default 0,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  check (escritura <> 'columna' or (tabla_destino is not null and columna_destino is not null)),
  check (tipo_dato <> 'opcion' or jsonb_typeof(opciones) = 'array')
);

-- La columna destino tiene que existir de verdad: evita catálogos que apunten a nada.
create or replace function fn_validar_campo_catalogo() returns trigger
language plpgsql as $$
begin
  if new.escritura = 'columna' and not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = new.tabla_destino and column_name = new.columna_destino
  ) then
    raise exception 'La columna %.% no existe', new.tabla_destino, new.columna_destino;
  end if;
  return new;
end $$;

drop trigger if exists trg_validar_campo_catalogo on catalogo_campos;
create trigger trg_validar_campo_catalogo before insert or update on catalogo_campos
  for each row execute function fn_validar_campo_catalogo();

create table if not exists atributos_valores (
  id bigint generated by default as identity primary key,
  entidad text not null check (entidad in ('contrato', 'unidad')),
  registro_id bigint not null,
  campo_id bigint not null references catalogo_campos(id),
  valor jsonb not null,
  updated_at timestamptz not null default now(),
  unique (entidad, registro_id, campo_id)
);
create index if not exists atributos_valores_registro_idx on atributos_valores(entidad, registro_id);

create table if not exists extracciones (
  id bigint generated by default as identity primary key,
  documento_id bigint not null references documentos(id) on delete cascade,
  tipo_documento tipo_documento not null,
  estado text not null default 'procesando'
    check (estado in ('procesando', 'borrador', 'confirmado', 'descartado', 'error')),
  -- {clave: {valor, confianza (0-1), pagina, texto}}
  datos jsonb not null default '{}'::jsonb,
  valores_finales jsonb,
  resolucion jsonb,                        -- {unidad_id, inquilino: {modo, id}}
  contrato_id bigint references contratos(id) on delete set null,
  modelo text,
  error text,
  creado_por text,
  confirmado_por text,
  confirmado_en timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists extracciones_documento_idx on extracciones(documento_id);
create index if not exists extracciones_estado_idx on extracciones(estado);

create table if not exists solicitudes_campo (
  id bigint generated by default as identity primary key,
  tipo_documento tipo_documento not null,
  etiqueta text not null,
  clave_sugerida text,
  tipo_dato text not null check (tipo_dato in ('texto', 'numero', 'moneda', 'fecha', 'booleano', 'opcion')),
  descripcion text,
  ejemplo text,
  estado text not null default 'pendiente' check (estado in ('pendiente', 'aprobada', 'rechazada')),
  propuesto_por text,
  revisado_por text,
  motivo_revision text,
  campo_id bigint references catalogo_campos(id),
  created_at timestamptz not null default now()
);

create table if not exists auditoria (
  id bigint generated by default as identity primary key,
  usuario text,
  extraccion_id bigint references extracciones(id) on delete set null,
  tabla text not null,
  registro_id bigint,
  columna text not null,
  valor_anterior jsonb,
  valor_nuevo jsonb,
  origen text not null check (origen in ('ia', 'humano', 'sistema')),
  created_at timestamptz not null default now()
);
create index if not exists auditoria_registro_idx on auditoria(tabla, registro_id);

-- Resultado del revisor de cláusulas (reglas deterministas + revisión semántica).
create table if not exists revisiones_contrato (
  id bigint generated by default as identity primary key,
  contrato_id bigint references contratos(id) on delete cascade,
  extraccion_id bigint references extracciones(id) on delete set null,
  hallazgos jsonb not null default '[]'::jsonb,   -- [{regla, severidad, titulo, detalle, clausula, referencia_legal}]
  resumen text,
  created_at timestamptz not null default now()
);
create index if not exists revisiones_contrato_idx on revisiones_contrato(contrato_id);

