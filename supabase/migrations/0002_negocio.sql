-- 0002 · Modelo de negocio: propietarios, edificios, unidades, inquilinos, contratos, pagos, incidencias

do $$ begin
  create type tipo_unidad as enum
    ('piso', 'atico', 'duplex', 'estudio', 'chalet', 'habitacion', 'local', 'oficina', 'garaje', 'trastero');
exception when duplicate_object then null; end $$;

do $$ begin
  create type operacion_tipo as enum ('alquiler', 'venta', 'temporada', 'habitaciones');
exception when duplicate_object then null; end $$;

do $$ begin
  create type estado_unidad as enum ('disponible', 'alquilada', 'reservada', 'reforma', 'vendida');
exception when duplicate_object then null; end $$;

do $$ begin
  create type tipo_contrato as enum ('vivienda_habitual', 'temporada', 'habitacion', 'local', 'compraventa');
exception when duplicate_object then null; end $$;

do $$ begin
  create type estado_contrato as enum ('borrador', 'vigente', 'finalizado', 'rescindido');
exception when duplicate_object then null; end $$;

create table if not exists propietarios (
  id bigint generated by default as identity primary key,
  tipo_persona text not null check (tipo_persona in ('fisica', 'sociedad')),
  nombre text not null,
  documento text not null unique,          -- DNI/NIE o CIF
  email text,
  telefono text,
  created_at timestamptz not null default now()
);

create table if not exists edificios (
  id bigint generated by default as identity primary key,
  referencia text unique,
  nombre text,
  direccion text not null,
  codigo_postal text,
  municipio_id integer not null references municipios(id),
  distrito_id integer references distritos(id),
  barrio_id integer references barrios(id),
  lat numeric(9, 6),
  lng numeric(9, 6),
  anio_construccion smallint check (anio_construccion between 1700 and 2100),
  plantas smallint check (plantas > 0),
  ascensor boolean not null default false,
  garaje boolean not null default false,
  portero boolean not null default false,
  piscina boolean not null default false,
  administrador_fincas text,
  gestiona_comunidad boolean not null default false,
  cuota_comunidad_media numeric(8, 2) check (cuota_comunidad_media >= 0),
  created_at timestamptz not null default now()
);
create index if not exists edificios_municipio_idx on edificios(municipio_id);
create index if not exists edificios_distrito_idx on edificios(distrito_id);
create index if not exists edificios_direccion_trgm on edificios using gin (norm(direccion) gin_trgm_ops);

create table if not exists unidades (
  id bigint generated by default as identity primary key,
  referencia text unique,
  edificio_id bigint not null references edificios(id) on delete restrict,
  unidad_padre_id bigint references unidades(id) on delete cascade,  -- habitación dentro de un piso compartido
  propietario_id bigint references propietarios(id),
  planta text,
  puerta text,
  tipo tipo_unidad not null,
  operacion operacion_tipo not null,
  estado estado_unidad not null default 'disponible',
  superficie_m2 numeric(8, 2) check (superficie_m2 > 0),
  habitaciones smallint check (habitaciones >= 0),
  banos smallint check (banos >= 0),
  precio_alquiler numeric(10, 2) check (precio_alquiler >= 0),
  precio_venta numeric(12, 2) check (precio_venta >= 0),
  precio_temporada_mes numeric(10, 2) check (precio_temporada_mes >= 0),
  amueblado boolean not null default false,
  admite_mascotas boolean not null default false,
  terraza boolean not null default false,
  certificado_energetico char(1) check (certificado_energetico in ('A', 'B', 'C', 'D', 'E', 'F', 'G')),
  certificado_caducidad date,
  referencia_catastral text,
  descripcion text,
  descripcion_embedding vector(768),
  fecha_disponible date,
  created_at timestamptz not null default now()
);
create index if not exists unidades_edificio_idx on unidades(edificio_id);
create index if not exists unidades_estado_idx on unidades(estado, operacion);
create index if not exists unidades_padre_idx on unidades(unidad_padre_id);
create index if not exists unidades_propietario_idx on unidades(propietario_id);
create index if not exists unidades_embedding_idx
  on unidades using hnsw (descripcion_embedding vector_cosine_ops);

create table if not exists inquilinos (
  id bigint generated by default as identity primary key,
  nombre text not null,
  apellidos text not null,
  documento_tipo text not null check (documento_tipo in ('DNI', 'NIE', 'PASAPORTE')),
  documento text not null unique,
  email text,
  telefono text,
  fecha_nacimiento date,
  nacionalidad text,
  profesion text,
  ingresos_mensuales numeric(10, 2) check (ingresos_mensuales >= 0),
  created_at timestamptz not null default now()
);

-- Clientes del CRM (interesados en alquilar, comprar o invertir). Los compradores firman compraventas.
create table if not exists clientes (
  id bigint generated by default as identity primary key,
  nombre text not null,
  email text,
  telefono text,
  tipo text not null check (tipo in ('inquilino', 'comprador', 'inversor')),
  notas text,
  notas_embedding vector(768),
  created_at timestamptz not null default now()
);

create table if not exists contratos (
  id bigint generated by default as identity primary key,
  referencia text unique,
  unidad_id bigint not null references unidades(id) on delete restrict,
  inquilino_id bigint references inquilinos(id),
  cliente_id bigint references clientes(id),            -- comprador en compraventas
  tipo tipo_contrato not null,
  estado estado_contrato not null default 'vigente',
  fecha_firma date,
  fecha_inicio date not null,
  fecha_fin date,
  renta_mensual numeric(10, 2) check (renta_mensual >= 0),
  fianza numeric(10, 2) check (fianza >= 0),
  garantia_adicional numeric(10, 2) check (garantia_adicional >= 0),
  fianza_depositada boolean not null default false,
  fecha_deposito_fianza date,
  indice_actualizacion text not null default 'ninguno' check (indice_actualizacion in ('ninguno', 'ipc', 'irav', 'fijo')),
  dia_pago smallint check (dia_pago between 1 and 31),
  precio_venta numeric(12, 2) check (precio_venta >= 0),
  prorrogas smallint not null default 0,
  documento_id bigint,                                  -- FK a documentos (se añade en 0003)
  created_at timestamptz not null default now(),
  check (fecha_fin is null or fecha_fin > fecha_inicio),
  -- alquileres: inquilino obligatorio; compraventas: comprador obligatorio
  check ((tipo = 'compraventa' and cliente_id is not null and inquilino_id is null)
      or (tipo <> 'compraventa' and inquilino_id is not null)),
  check (tipo <> 'compraventa' or precio_venta is not null),
  check (tipo = 'compraventa' or (fecha_fin is not null and renta_mensual is not null)),
  -- una unidad no puede tener dos contratos de alquiler solapados
  constraint contratos_sin_solape exclude using gist (
    unidad_id with =,
    daterange(fecha_inicio, fecha_fin, '[]') with &&
  ) where (tipo <> 'compraventa' and estado <> 'borrador')
);
create index if not exists contratos_unidad_idx on contratos(unidad_id);
create index if not exists contratos_inquilino_idx on contratos(inquilino_id);
create index if not exists contratos_fin_idx on contratos(fecha_fin) where estado = 'vigente';

create table if not exists pagos (
  id bigint generated by default as identity primary key,
  contrato_id bigint not null references contratos(id) on delete cascade,
  periodo date not null,                                -- primer día del mes que se paga
  importe numeric(10, 2) not null check (importe >= 0),
  fecha_vencimiento date not null,
  fecha_pago date,
  estado text not null check (estado in ('pagado', 'pendiente', 'impagado')),
  dias_retraso integer generated always as (
    case when fecha_pago is null then null else greatest(fecha_pago - fecha_vencimiento, 0) end
  ) stored,
  unique (contrato_id, periodo)
);
create index if not exists pagos_estado_idx on pagos(estado, fecha_vencimiento);

create table if not exists proveedores (
  id bigint generated by default as identity primary key,
  nombre text not null,
  cif text,
  categoria text not null,
  telefono text,
  email text
);

create table if not exists incidencias (
  id bigint generated by default as identity primary key,
  unidad_id bigint references unidades(id) on delete cascade,
  edificio_id bigint references edificios(id) on delete cascade,
  categoria text not null check (categoria in (
    'fontaneria', 'electricidad', 'calefaccion', 'ascensor', 'cerrajeria',
    'humedades', 'electrodomesticos', 'plagas', 'pintura', 'otros')),
  prioridad text not null check (prioridad in ('baja', 'media', 'alta', 'urgente')),
  estado text not null check (estado in ('abierta', 'en_curso', 'cerrada')),
  descripcion text not null,
  coste numeric(10, 2) check (coste >= 0),
  proveedor_id bigint references proveedores(id),
  fecha_apertura date not null,
  fecha_cierre date,
  check (unidad_id is not null or edificio_id is not null),
  check (fecha_cierre is null or fecha_cierre >= fecha_apertura)
);
create index if not exists incidencias_estado_idx on incidencias(estado, prioridad);
create index if not exists incidencias_unidad_idx on incidencias(unidad_id);

create table if not exists gastos (
  id bigint generated by default as identity primary key,
  edificio_id bigint references edificios(id) on delete cascade,
  unidad_id bigint references unidades(id) on delete cascade,
  concepto text not null check (concepto in ('ibi', 'comunidad', 'seguro', 'derrama', 'suministros', 'otros')),
  importe numeric(10, 2) not null check (importe >= 0),
  fecha date not null,
  check (edificio_id is not null or unidad_id is not null)
);

drop trigger if exists trg_ref_edificios on edificios;
