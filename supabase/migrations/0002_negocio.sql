  for each row execute function fn_set_referencia('E');
drop trigger if exists trg_ref_unidades on unidades;
create trigger trg_ref_unidades before insert on unidades
  for each row execute function fn_set_referencia('U');
drop trigger if exists trg_ref_contratos on contratos;
create trigger trg_ref_contratos before insert on contratos
  for each row execute function fn_set_referencia('C');
