-- 0012 · Intentos bloqueados por las barreras del asistente (para que el administrador los revise)
create table if not exists chat_bloqueos (
  id bigint generated by default as identity primary key,
  motivo text not null check (motivo in ('manipulacion', 'formato', 'fuera_de_alcance', 'demasiado_largo')),
  mensaje text not null,
  usuario text,
  created_at timestamptz not null default now()
);
create index if not exists chat_bloqueos_idx on chat_bloqueos(created_at desc);
alter table chat_bloqueos enable row level security;
