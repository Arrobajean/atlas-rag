-- 0001 · Extensiones, utilidades y geografía de la Comunidad de Madrid
-- Ejecutar en Supabase > SQL Editor (o con `pnpm db:migrate` si hay SUPABASE_DB_URL).

create extension if not exists vector;
create extension if not exists unaccent with schema public;
create extension if not exists pg_trgm with schema public;
create extension if not exists btree_gist with schema public;

-- Normaliza texto para comparar: minúsculas y sin tildes ("Chamberí" = "chamberi").
-- Lleva su propio search_path: PG17 ejecuta CREATE INDEX con un search_path vacío y, sin esto,
-- no encontraría unaccent al indexar norm(...).
create or replace function norm(t text) returns text
language sql immutable parallel safe
set search_path = public, extensions, pg_temp
as $$ select lower(unaccent(coalesce(t, ''))) $$;

-- Referencia legible (U-00012, C-00345…) a partir del id de identidad.
create or replace function fn_set_referencia() returns trigger
language plpgsql as $$
begin
  if new.referencia is null then
    new.referencia := tg_argv[0] || '-' || lpad(new.id::text, 5, '0');
  end if;
  return new;
end $$;

-- Zonas propias (no oficiales): agrupan distritos de la capital y municipios de la Comunidad.
create table if not exists zonas (
  id smallint generated by default as identity primary key,
  nombre text not null unique,
  descripcion text
);

create table if not exists municipios (
  id integer generated by default as identity primary key,
  nombre text not null unique,
  zona_id smallint not null references zonas(id),
  es_capital boolean not null default false,
  poblacion integer
);
create index if not exists municipios_zona_idx on municipios(zona_id);

-- Distritos: solo la capital tiene división oficial en distritos y barrios.
create table if not exists distritos (
  id integer generated by default as identity primary key,
  municipio_id integer not null references municipios(id),
  nombre text not null,
  zona_id smallint not null references zonas(id),
  unique (municipio_id, nombre)
);

create table if not exists barrios (
  id integer generated by default as identity primary key,
  distrito_id integer not null references distritos(id),
  nombre text not null,
  unique (distrito_id, nombre)
);

-- Diccionario de sinónimos para que el chat entienda "el sur", "el centro", "Vallecas"…
create table if not exists sinonimos_lugar (
  id integer generated by default as identity primary key,
  termino text not null,
  entidad text not null check (entidad in ('zona', 'municipio', 'distrito', 'barrio')),
  entidad_id integer not null,
  unique (termino, entidad, entidad_id)
);
create index if not exists sinonimos_lugar_termino_idx on sinonimos_lugar(norm(termino));
